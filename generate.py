def worst_case(m, n):
    """Худший случай: общих элементов нет, поэтому алгоритм не может остановиться раньше.
    b - чётные числа 0, 2, 4, ...; a - нечётные, равномерно разложенные по диапазону b."""
    b = [2 * i for i in range(n)]
    a = [2 * ((k * n) // m) + 1 for k in range(m)]
    return a, b
